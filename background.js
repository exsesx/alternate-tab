const STORAGE_KEY = 'tabsHistory';
const MAX_HISTORY_SIZE = 10;
let operation = Promise.resolve();
let cachedHistory;
let persistence = Promise.resolve();
let verifiedWindow;
let windowRevision = 0;
let activatingTabId;

function invalidateWindow() {
  verifiedWindow = undefined;
  windowRevision++;
}

// Queue the whole operation, including API reads and focus changes. Queuing only
// storage writes lets consecutive commands choose the same target.
function enqueue(task) {
  operation = operation.then(task).catch(error => {
    console.error('Alternate Tab:', error);
  });
  return operation;
}

function remember(history, tab) {
  return [
    { tabId: tab.id, windowId: tab.windowId },
    ...history.filter(entry => entry.tabId !== tab.id),
  ].slice(0, MAX_HISTORY_SIZE);
}

function saveHistory(history) {
  cachedHistory = history;
  // Persist in order without putting storage latency on the next switch.
  // Each queued write owns its snapshot; later events replace, never mutate it.
  persistence = persistence.then(() => chrome.storage.session.set({ [STORAGE_KEY]: history }))
    .catch(error => console.error('Alternate Tab history persistence:', error));
}

async function getHistory() {
  if (cachedHistory) return cachedHistory;
  const stored = (await chrome.storage.session.get(STORAGE_KEY))[STORAGE_KEY];
  if (Array.isArray(stored) && stored.length) return (cachedHistory = stored);

  // Tab IDs belong to a browser session. After reload/restart, recover from
  // Chrome's recency data rather than reuse IDs persisted by another session.
  const tabs = await chrome.tabs.query({ windowType: 'normal' });
  tabs.sort((a, b) => (b.lastAccessed || 0) - (a.lastAccessed || 0));
  cachedHistory = tabs.slice(0, MAX_HISTORY_SIZE).map(tab => ({
    tabId: tab.id, windowId: tab.windowId,
  }));
  return cachedHistory;
}

async function recordActiveTab(tabId) {
  // Our switch already records its target. Its activation callback adds nothing.
  if (cachedHistory?.[0]?.tabId === tabId) return;
  let tab;
  let window;
  try {
    tab = await chrome.tabs.get(tabId);
    window = await chrome.windows.get(tab.windowId);
  } catch {
    return; // The tab/window may have closed while this event was queued.
  }
  // An active tab exists in every window. Only the focused one was visited.
  // This also ignores stale events generated by an earlier switch.
  if (!tab.active || !window.focused || window.type !== 'normal') return;
  await saveHistory(remember(await getHistory(), tab));
}

async function recordFocusedWindow(windowId) {
  if (windowId === chrome.windows.WINDOW_ID_NONE) return;
  const [tab] = await chrome.tabs.query({ active: true, windowId });
  if (tab) await recordActiveTab(tab.id);
}

async function switchToPreviousTab() {
  const revision = windowRevision;
  // Use a normal browser window even when a popup/PiP window has focus.
  let history = cachedHistory;
  let currentWindow = verifiedWindow;
  if (!history || !currentWindow) {
    [history, currentWindow] = await Promise.all([
      getHistory(),
      chrome.windows.getLastFocused({ windowTypes: ['normal'], populate: true }),
    ]);
  }
  const currentTab = currentWindow.tabs.find(tab => tab.active);
  if (!currentTab) return;
  history = remember(history, currentTab);

  for (const entry of history.slice(1)) {
    let target;
    let targetWindow;
    try {
      target = currentWindow.tabs.find(tab => tab.id === entry.tabId)
        || await chrome.tabs.get(entry.tabId);
      targetWindow = target.windowId === currentWindow.id
        ? currentWindow
        : await chrome.windows.get(target.windowId);
    } catch {
      history = history.filter(item => item.tabId !== entry.tabId);
      continue;
    }
    if (targetWindow.type !== 'normal') {
      history = history.filter(item => item.tabId !== entry.tabId);
      continue;
    }

    try {
      // Select first, so focusing the window never records an unrelated tab.
      activatingTabId = target.id;
      try {
        target = await chrome.tabs.update(target.id, { active: true });
      } finally {
        activatingTabId = undefined;
      }
      if (targetWindow.state === 'minimized') {
        await chrome.windows.update(target.windowId, { state: 'normal' });
      }
      if (!targetWindow.focused) {
        await chrome.windows.update(target.windowId, { focused: true });
      }
    } catch (error) {
      invalidateWindow();
      // Do not silently try another tab after a partially completed switch.
      await saveHistory(history);
      throw error;
    }
    // Already-active tabs in other windows do not emit onActivated. Commit
    // explicitly before allowing the next keyboard/toolbar command to run.
    await saveHistory(remember(history, target));
    // Keep only a focused normal window we actually inspected. Any intervening
    // external event invalidates it synchronously, before the next command.
    if (revision === windowRevision && currentWindow.focused && target.windowId === currentWindow.id) {
      verifiedWindow = {
        ...currentWindow,
        tabs: currentWindow.tabs.map(tab => ({ ...tab, active: tab.id === target.id })),
      };
    } else {
      verifiedWindow = undefined;
    }
    return;
  }
  await saveHistory(history);
}

chrome.commands.onCommand.addListener(command => {
  if (command === 'switch-to-previous-tab') return enqueue(switchToPreviousTab);
});
chrome.action.onClicked.addListener(() => enqueue(switchToPreviousTab));
chrome.tabs.onActivated.addListener(({ tabId }) => {
  if (tabId !== activatingTabId) invalidateWindow();
  return enqueue(() => recordActiveTab(tabId));
});
chrome.windows.onFocusChanged.addListener(windowId => {
  invalidateWindow();
  return enqueue(() => recordFocusedWindow(windowId));
});
chrome.tabs.onAttached.addListener(invalidateWindow);
chrome.tabs.onDetached.addListener(invalidateWindow);
chrome.tabs.onRemoved.addListener(tabId => {
  invalidateWindow();
  return enqueue(async () => {
    saveHistory((await getHistory()).filter(entry => entry.tabId !== tabId));
  });
});
chrome.tabs.onReplaced.addListener((addedTabId, removedTabId) => {
  invalidateWindow();
  return enqueue(async () => {
    const history = await getHistory();
    const tab = await chrome.tabs.get(addedTabId);
    saveHistory(history.filter(entry => entry.tabId !== addedTabId).map(entry =>
      entry.tabId === removedTabId ? { tabId: addedTabId, windowId: tab.windowId } : entry
    ));
  });
});

async function seedHistory() {
  const history = await getHistory();
  const window = await chrome.windows.getLastFocused({ windowTypes: ['normal'] });
  const [tab] = await chrome.tabs.query({ active: true, windowId: window.id });
  await saveHistory(tab ? remember(history, tab) : history);
}
chrome.runtime.onInstalled.addListener(() => enqueue(seedHistory));
chrome.runtime.onStartup.addListener(() => enqueue(seedHistory));
